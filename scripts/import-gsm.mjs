import fs from "node:fs";
import path from "node:path";
import { createClient } from "@supabase/supabase-js";

const SUBJECT_CODE = "gsm";
const SUBJECT_SLUG = "gsm-phone-maintenance-and-repair";
const SUBJECT_DISPLAY_NAME = "GSM Phone Maintenance & Repair";

function loadEnv(envPath) {
  if (!fs.existsSync(envPath)) return;

  const lines = fs.readFileSync(envPath, "utf8").split(/\r?\n/);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;

    const separatorIndex = trimmed.indexOf("=");
    if (separatorIndex === -1) continue;

    const key = trimmed.slice(0, separatorIndex).trim();
    const rawValue = trimmed.slice(separatorIndex + 1).trim();
    const value = rawValue.replace(/^['"]|['"]$/g, "");

    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}

function parseArgs(argv) {
  const options = {
    input: path.resolve("C:\\Users\\Gm_Bi\\Downloads\\waec\\GSM_all_years.txt"),
    dryRun: false,
    sqlOut: "",
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];

    if (arg === "--dry-run") {
      options.dryRun = true;
      continue;
    }

    if (arg === "--input" && argv[index + 1]) {
      options.input = path.resolve(argv[index + 1]);
      index += 1;
      continue;
    }

    if (arg === "--sql-out" && argv[index + 1]) {
      options.sqlOut = path.resolve(argv[index + 1]);
      index += 1;
    }
  }

  return options;
}

function parseTxtFile(content) {
  const normalized = content.replace(/\r\n/g, "\n");
  const blockPattern =
    /^===== SUBJECT: (.+?) \| YEAR: (\d{4}) \| PAGE: (\d+) =====\n([\s\S]*?)(?=^===== SUBJECT: |\z)/gm;
  const entries = [];
  let match;

  while ((match = blockPattern.exec(normalized)) !== null) {
    const [, subject, yearText, pageText, blockBody] = match;
    const year = Number(yearText);
    const pageNumber = Number(pageText);

    const urlMatch = blockBody.match(/^URL:\s*(.+)$/m);
    const sourceUrl = urlMatch ? urlMatch[1].trim() : null;
    const [, contentAfterMeta = ""] = blockBody.split(/Images on this page:\s*\d+\n/i);
    const trimmedBody = contentAfterMeta.trim();

    if (!trimmedBody) {
      continue;
    }

    const answerSplit = trimmedBody.split(/\nAnswer Notes:\n/i);
    const questionText = answerSplit[0].trim();
    const answerNotes = (answerSplit[1] ?? "").trim();
    const questionNumberMatch = questionText.match(/Question\s+(\d+)/i);

    entries.push({
      subject,
      exam_year: year,
      page_number: pageNumber,
      question_number: questionNumberMatch ? questionNumberMatch[1] : String(pageNumber),
      title: `${subject} ${year}`,
      question_text: questionText,
      answer_notes: answerNotes || null,
      source_url: sourceUrl,
      source_payload: {
        import_format: "txt",
        source_subject: subject,
        page_number: pageNumber,
      },
    });
  }

  return entries;
}

function escapeSql(value) {
  return value.replaceAll("'", "''");
}

function buildSql(entries) {
  const lines = [
    "-- Generated by scripts/import-gsm.mjs",
    "begin;",
    "",
    `insert into public.question_subjects (code, slug, display_name, description)`,
    `values ('${SUBJECT_CODE}', '${SUBJECT_SLUG}', '${escapeSql(SUBJECT_DISPLAY_NAME)}', '${escapeSql("Imported WAEC GSM question bank")}')`,
    "on conflict (code) do update",
    "set slug = excluded.slug,",
    "    display_name = excluded.display_name,",
    "    description = excluded.description;",
    "",
    "with gsm_subject as (",
    `  select id from public.question_subjects where code = '${SUBJECT_CODE}'`,
    ")",
  ];

  for (const entry of entries) {
    lines.push(
      "insert into public.question_bank_entries (",
      "  subject_id, exam_year, page_number, question_number, title, question_text, answer_notes, source_url, source_payload",
      ")",
      "select",
      `  gsm_subject.id, ${entry.exam_year}, ${entry.page_number}, '${escapeSql(entry.question_number)}', '${escapeSql(entry.title)}',`,
      `  '${escapeSql(entry.question_text)}', ${
        entry.answer_notes ? `'${escapeSql(entry.answer_notes)}'` : "null"
      }, ${entry.source_url ? `'${escapeSql(entry.source_url)}'` : "null"},`,
      `  '${escapeSql(JSON.stringify(entry.source_payload))}'::jsonb`,
      "from gsm_subject",
      "on conflict (subject_id, exam_year, page_number, source_url) do update",
      "set question_number = excluded.question_number,",
      "    title = excluded.title,",
      "    question_text = excluded.question_text,",
      "    answer_notes = excluded.answer_notes,",
      "    source_payload = excluded.source_payload;",
      ""
    );
  }

  lines.push("commit;");
  return `${lines.join("\n")}\n`;
}

async function importToSupabase(entries) {
  loadEnv(path.resolve(".env.local"));

  if (!process.env.SUPABASE_URL || !process.env.SUPABASE_SERVICE_ROLE_KEY) {
    throw new Error("Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local");
  }

  const supabase = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, {
    auth: { autoRefreshToken: false, persistSession: false },
  });

  const { data: subject, error: subjectError } = await supabase
    .from("question_subjects")
    .upsert(
      {
        code: SUBJECT_CODE,
        slug: SUBJECT_SLUG,
        display_name: SUBJECT_DISPLAY_NAME,
        description: "Imported WAEC GSM question bank",
      },
      { onConflict: "code" }
    )
    .select("id")
    .single();

  if (subjectError) {
    throw subjectError;
  }

  const rows = entries.map((entry) => ({
    subject_id: subject.id,
    exam_year: entry.exam_year,
    page_number: entry.page_number,
    question_number: entry.question_number,
    title: entry.title,
    question_text: entry.question_text,
    answer_notes: entry.answer_notes,
    source_url: entry.source_url,
    source_payload: entry.source_payload,
  }));

  const { error: rowError } = await supabase
    .from("question_bank_entries")
    .upsert(rows, { onConflict: "subject_id,exam_year,page_number,source_url" });

  if (rowError) {
    throw rowError;
  }
}

async function main() {
  const options = parseArgs(process.argv.slice(2));

  if (!fs.existsSync(options.input)) {
    throw new Error(`Input file not found: ${options.input}`);
  }

  const content = fs.readFileSync(options.input, "utf8");
  const entries = parseTxtFile(content);

  if (entries.length === 0) {
    throw new Error("No GSM entries were parsed from the input file.");
  }

  const years = [...new Set(entries.map((entry) => entry.exam_year))].sort((a, b) => a - b);

  console.log(
    JSON.stringify(
      {
        subject: SUBJECT_DISPLAY_NAME,
        input: options.input,
        parsedEntries: entries.length,
        years,
      },
      null,
      2
    )
  );

  if (options.sqlOut) {
    fs.writeFileSync(options.sqlOut, buildSql(entries), "utf8");
    console.log(`Wrote SQL seed file to ${options.sqlOut}`);
  }

  if (!options.dryRun) {
    await importToSupabase(entries);
    console.log("Imported GSM question bank into Supabase.");
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
